#!/usr/bin/env node
/**
 * check-token-usage.js — the theme's mechanical rules over its own sources.
 *
 * The doctrine these implement is in CLAUDE.md: "when you add a design
 * decision, publish it and assert it". Every value the generator publishes and
 * a guard compares has stayed correct across a major redesign; every value
 * left to prose has moved. Drift here has never been a discipline problem, it
 * is a coverage problem — so each rule below exists because the thing it
 * checks had already silently broken at least once.
 *
 * 1. NAMES. Fail when any var(--token) doesn't resolve to a defined custom
 *    property. Undefined tokens fail silently at runtime.
 *
 *    A token counts as defined when it is declared:
 *     - in any SCSS file (`--name: …;`),
 *     - inline in a template (`--name:` in view/**.phtml — e.g. the brand
 *       seeds injected by layout.phtml), or
 *     - at runtime by theme JS (`setProperty('--name', …)`).
 *
 * 2. TYPE SCALE. Fail on a `font-size` carrying an ABSOLUTE literal (px / rem
 *    / pt) instead of a --text-* token — anywhere in the value, including
 *    inside clamp() / min() / max() / calc(). The theme is the source of truth
 *    for the scale, and it was reaching around its own scale in two places
 *    while the modules did it a hundred times ("when the source of truth
 *    reaches around its own scale twice, the consumers will reach around it a
 *    hundred times" — design review 2026-08, F3). Relative units (em, %,
 *    unitless, vw) stay legal: they scale WITH the token the cascade already
 *    set, so they don't fork the scale.
 *
 * 3. BREAKPOINT CONTRACT. `min-width` sits ON a published breakpoint;
 *    `max-width` sits at breakpoint − 1. Both modules' guards already enforce
 *    this on their own CSS; until 2.14 the source of truth did not enforce it
 *    on itself and carried two spellings of the "below" half.
 *
 * 4. PRIMARY IS AN ACCENT, NOT A BODY-TEXT COLOUR. `--primary` on
 *    `--background` measures 4.40:1 — under AA for normal-size text, fine as a
 *    large-text / non-text accent. See the narrow heuristic documented at the
 *    rule itself, including what it deliberately cannot see.
 *
 * 5. SUBSTITUTION SCOPE, both directions. A custom property is substituted at
 *    computed-value time on the element that DECLARES it.
 *      (a) A light-scope token whose value references a token the dark block
 *          redeclares must ITSELF be redeclared in the dark block, or dark
 *          pages inherit the light composition forever.
 *      (b) Every token the dark mixins declare must also be declared in the
 *          light mixins, or `body[data-theme="light"]` has nothing to win back
 *          with against a system-dark override already sitting on :root.
 *    (a) has bitten the repo three times (the --type-* map, the composed focus
 *    tokens, --panel-shadow + the --glow-* halos); every time tokens.json
 *    published the correct dark value while the browser painted the light one.
 *    (b) is how the 2.13 focus fix stayed half-done for a release.
 *
 * 6. PWA THEME-COLOR. The two <meta name="theme-color"> values in
 *    view/layout/layout.phtml are hand-written copies of --surface, one per
 *    colour scheme. A <meta> cannot read a custom property, so the copy is
 *    unavoidable — but an unasserted copy is exactly the shape of drift this
 *    repo has been bitten by before. Compare against tokens.json.
 *
 * 6b. THE SVG FAVICON. asset/img/pwa/favicon.svg is generated by
 *    `npm run build:icons` and states the LIGHT --surface as the ground it
 *    paints, in both colour schemes (2.17.1 dropped the dark variant: ZMO's
 *    negative is drawn for a poster and fell apart at 32px). The PNGs beside it
 *    hold the same colour in pixels, where nothing can compare it — the SVG is
 *    text, so assert the copy that CAN be read and the whole set is known to be
 *    stale together.
 *
 * 6c. THE HERO DUOTONE. The manifest's install-dialog screenshots are the
 *    homepage hero, composited offline by `npm run build:icons` from the
 *    numbers in lib/hero-duotone.js — a copy of _banner.scss that nothing can
 *    notice going stale, because the result lives in pixels. Assert the
 *    stylesheet still spells the same ground mix, filter chain and plate
 *    opacity.
 *
 * 7. DESIGN.md FRONTMATTER. The Impeccable artifact's YAML frontmatter mirrors
 *    tokens.json LIGHT values. tokens.json is normative; the frontmatter is
 *    generated by `/impeccable document`. Assert the two agree (roadmap
 *    Phase 4, item 1) so a token change can't leave the design tooling reading
 *    a stale palette.
 */
'use strict';

const fs = require('fs');
const path = require('path');

// Shared with build-tokens.js, which publishes the same set as `names` in
// tokens.json so the sibling modules can run this check too — and which
// resolves the same cascade blocks rule 5 reads.
const {
    collectDefinedTokenNames,
    walk,
    extractMixinBody,
    extractRootBody,
    parseDecls,
} = require('./lib/theme-tokens');

const ROOT = path.join(__dirname, '..');
const SASS_DIR = path.join(ROOT, 'asset/sass');
const VARS_DIR = path.join(SASS_DIR, 'abstracts/variables');
const TOKENS_JSON = path.join(ROOT, 'tokens.json');
const LAYOUT_PHTML = path.join('view', 'layout', 'layout.phtml');
const DESIGN_MD = path.join(ROOT, 'DESIGN.md');

const defined = collectDefinedTokenNames(ROOT);

/** Blank out comments while preserving line numbers and byte offsets. */
function blankComments(src) {
    let out = '';
    for (let i = 0; i < src.length; i++) {
        // `//` line comment — but not the `//` in a bare url(https://…).
        if (src[i] === '/' && src[i + 1] === '/' && src[i - 1] !== ':') {
            while (i < src.length && src[i] !== '\n') { out += ' '; i++; }
            out += '\n';
        } else if (src[i] === '/' && src[i + 1] === '*') {
            const end = src.indexOf('*/', i + 2);
            const stop = end === -1 ? src.length : end + 2;
            for (; i < stop; i++) out += src[i] === '\n' ? '\n' : ' ';
            i--;
        } else {
            out += src[i];
        }
    }
    return out;
}

const failures = [];      // rules 1-3
const primaryText = [];   // rule 4
const scopeFailures = []; // rule 5

/* ------------------------------------------------------------------ */
/*  Rules 1-3: per-line scan of asset/sass                             */
/* ------------------------------------------------------------------ */

const USE_RE = /var\(\s*(--[a-z0-9-]+)/gi;
// Any absolute length inside a font-size value. Anchoring on the whole value
// (not just its first token) is what closes the clamp() blind spot:
// `font-size: clamp(4rem, 15vw, 8rem)` declared a private 64-128px scale that
// the old first-token match could not see. Relative units are untouched.
const FONT_SIZE_RE = /font-size:\s*([^;{}]+)/gi;
const ABS_LENGTH_RE = /(?<![\w-])(-?\d*\.?\d+(?:px|rem|pt))(?![\w-])/i;
// Files that legitimately set absolute sizes: the vendored normalize reset
// (it predates the scale and its job is to neutralise UA defaults) and the
// print sheet (physical units — pt — have no screen token).
const TYPE_SCALE_EXEMPT = [
    path.join('asset', 'sass', 'generic', '_normalize.scss'),
    path.join('asset', 'sass', 'utilities', '_print.scss'),
];

// The six published breakpoints, read from the file that defines them so this
// guard can never disagree with tokens.json about what the contract is.
const BP_NAMES = Object.keys(
    Object.fromEntries(
        [...fs.readFileSync(path.join(VARS_DIR, '_breakpoints.scss'), 'utf8')
            .matchAll(/^\$([\w-]+)\s*:\s*(\d+)px\s*;/gm)]
            .map((m) => [m[1], m[2]]),
    ),
);
const WIDTH_FEATURE_RE = /\((min|max)-width\s*:\s*([^)]+)\)/g;
// The condition text of every `@media` on a line.
//
// Scanned by hand rather than matched with `@media([^{]*)\{` because
// `@media (max-width: #{$md - 1px}) {` carries a `{` INSIDE the condition: the
// naive pattern stops at the interpolation, the condition it hands back has no
// closing paren, and the whole max-width half of the contract is silently never
// checked. (It was, here, until 2.14 — the min-width half passed and looked
// like coverage.) Interpolation depth is tracked so the real opening brace is
// the one that ends the condition.
function mediaConditions(line) {
    const out = [];
    let i = 0;
    while ((i = line.indexOf('@media', i)) !== -1) {
        i += '@media'.length;
        let depth = 0;
        let cond = '';
        for (; i < line.length; i++) {
            const c = line[i];
            if (c === '#' && line[i + 1] === '{') depth++;
            else if (c === '{' && depth === 0) break;
            else if (c === '}' && depth > 0) depth--;
            cond += c;
        }
        out.push(cond);
    }
    return out;
}
// The one legal spelling of each half.
const MIN_OK = new RegExp(`^(?:#\\{)?\\$(?:${BP_NAMES.join('|')})\\}?$`);
const MAX_OK = new RegExp(`^#\\{\\s*\\$(?:${BP_NAMES.join('|')})\\s*-\\s*1px\\s*\\}$`);

for (const file of walk(SASS_DIR, ['.scss'])) {
    const rel = path.relative(ROOT, file);
    const typeScaleExempt = TYPE_SCALE_EXEMPT.includes(rel);
    const src = blankComments(fs.readFileSync(file, 'utf8'));
    src.split('\n').forEach((line, i) => {
        const at = `${rel}:${i + 1}`;

        for (const m of line.matchAll(USE_RE)) {
            if (!defined.has(m[1])) {
                failures.push(`${at}  var(${m[1]}) is not defined anywhere`);
            }
        }

        if (!typeScaleExempt) {
            for (const m of line.matchAll(FONT_SIZE_RE)) {
                const hit = ABS_LENGTH_RE.exec(m[1]);
                if (hit) {
                    failures.push(
                        `${at}  font-size: ${m[1].trim()} — the literal ${hit[1]} must come from a --text-* token`
                        + ' (--text-2xs is the floor; there is deliberately no 14px step)',
                    );
                }
            }
        }

        for (const cond of mediaConditions(line)) {
            for (const f of cond.matchAll(WIDTH_FEATURE_RE)) {
                const [, kind, raw] = f;
                const width = raw.trim();
                if (kind === 'min' && !MIN_OK.test(width)) {
                    failures.push(
                        `${at}  @media (min-width: ${width}) — min-width sits ON a published breakpoint:`
                        + ` use one of ${BP_NAMES.map((b) => '$' + b).join(', ')}`,
                    );
                } else if (kind === 'max' && !MAX_OK.test(width)) {
                    failures.push(
                        `${at}  @media (max-width: ${width}) — max-width sits at breakpoint − 1:`
                        + ' use #{$<bp> - 1px} (the `- 0.02px` spelling was retired in 2.14)',
                    );
                }
            }
        }
    });
}

/* ------------------------------------------------------------------ */
/*  Rule 4: --primary is an accent, never running body text            */
/*                                                                    */
/*  THE POLICY — docs/DESIGN-SYSTEM.md, "--primary is an accent, not */
/*  a text colour"; docs/DESIGN-PHILOSOPHY.md core principle 5:      */
/*  primary is fine for large display text, UI marks, states and       */
/*  links; it is not a colour for running body text on the page        */
/*  ground, where it measures 4.40:1 — under AA for normal sizes.      */
/*                                                                    */
/*  THE HEURISTIC, and why it is this narrow. Every one of the ~60     */
/*  current `color: var(--primary…)` sites is a link, a control, a     */
/*  state (:hover / .is-active / [aria-expanded]), a pseudo-element    */
/*  mark (interpunct, ::marker, chevron), a form control accent, or    */
/*  the 404 display numeral — all sanctioned. A rule phrased as "flag  */
/*  unless it looks interactive" would therefore be an ever-growing    */
/*  list of class-name exemptions: a rule that only ever gets weaker.  */
/*  So this one is phrased positively — flag only what positively      */
/*  looks like running prose — in two arms:                            */
/*                                                                    */
/*   A. The same declaration block also carries a long-form-reading    */
/*      marker. --font-serif-text, --line-height-relaxed and the       */
/*      --measure-* tokens exist for exactly one purpose: prose. A     */
/*      block that says "this is running text" and "paint it primary"  */
/*      in the same breath is the violation, whatever it is called.    */
/*   B. The rule's leaf selector is a bare prose ELEMENT (p, li, dd,   */
/*      blockquote, …) with no state, pseudo-element or interactive    */
/*      element anywhere in the chain. The leaf must be a bare tag, so */
/*      the exemption set stays small and closed instead of tracking   */
/*      class names.                                                   */
/*                                                                    */
/*  LIMITS — say them plainly rather than let the rule be mistaken for */
/*  a proof:                                                           */
/*   - A prose container named only by a class (`.article-body`) with  */
/*     none of the three markers is invisible to both arms. Arm A is   */
/*     the mitigation, not a guarantee.                                */
/*   - Selectors are resolved from Sass nesting; a chain that passes   */
/*     through a @mixin is not resolvable (the mixin's call sites are  */
/*     elsewhere), so arm B skips mixin bodies. Arm A still applies.   */
/*   - It checks the theme's Sass only. IwacSearch's scoped <style>    */
/*     blocks and IwacVisualizations' CSS are their own guards' job.   */
/*   - It says nothing about `background`, `border-color` or `fill` —  */
/*     primary as a non-text mark is sanctioned and common.            */
/* ------------------------------------------------------------------ */

const PROSE_MARKER_RE = /--font-serif-text|--line-height-relaxed|--measure-(?:narrow|base|wide)/;
const PROSE_LEAF_RE = /(?:^|[\s>+~])(p|li|dd|blockquote|figcaption|td|pre)(?::not\([^)]*\))*$/i;
const STATE_RE = /:(?:hover|focus|focus-visible|focus-within|active|visited|checked|target|disabled)\b|\[aria-(?:expanded|current|selected)|(?:^|[.\s>+~-])(?:is-)?(?:active|current|selected|open|expanded)\b/i;
const PSEUDO_ELEMENT_RE = /::?(?:before|after|marker|placeholder|selection|backdrop|first-letter|first-line)\b/i;
const INTERACTIVE_RE = /(?:^|[\s>+~,(])(?:a|button|input|select|textarea|summary|label)(?:[.:[\s>+~,)]|$)/i;

/**
 * Walk a SCSS file into declaration blocks, each carrying its resolved
 * selector chain. `#{…}` interpolation is skipped wholesale so the braces
 * inside `#{$md - 1px}` don't open and close phantom blocks.
 */
function parseBlocks(src) {
    const blocks = [];
    const stack = [];
    let frame = '';
    let line = 1;
    for (let i = 0; i < src.length; i++) {
        const ch = src[i];
        if (ch === '\n') { line++; frame += ' '; continue; }
        if (ch === '#' && src[i + 1] === '{') {
            let depth = 0;
            for (; i < src.length; i++) {
                if (src[i] === '{') depth++;
                else if (src[i] === '}') { depth--; if (depth === 0) break; }
                else if (src[i] === '\n') line++;
                frame += src[i];
            }
            frame += '}';
            continue;
        }
        if (ch === '{') {
            const block = { chain: [...stack, frame.trim()], decls: [] };
            blocks.push(block);
            stack.push(frame.trim());
            frame = '';
        } else if (ch === '}') {
            stack.pop();
            frame = '';
        } else if (ch === ';') {
            const decl = frame.trim();
            const m = /^([\w-]+)\s*:\s*([\s\S]+)$/.exec(decl);
            if (m) {
                const owner = blocks.find((b) => b.chain.length === stack.length
                    && b.chain.every((s, k) => s === stack[k]));
                if (owner) owner.decls.push({ prop: m[1], value: m[2].trim(), line });
            }
            frame = '';
        } else {
            frame += ch;
        }
    }
    return blocks;
}

for (const file of walk(SASS_DIR, ['.scss'])) {
    const rel = path.relative(ROOT, file);
    for (const block of parseBlocks(blankComments(fs.readFileSync(file, 'utf8')))) {
        const paints = block.decls.filter(
            (d) => d.prop === 'color' && /var\(\s*--primary/.test(d.value),
        );
        if (!paints.length) continue;

        const chain = block.chain.filter(Boolean);
        const chainText = chain.join(' ');
        const leaf = chain[chain.length - 1] || '';

        // Arm A — this block declares itself long-form reading.
        const marker = block.decls.find(
            (d) => d.prop !== 'color' && PROSE_MARKER_RE.test(d.value),
        );
        if (marker) {
            primaryText.push(
                `${rel}:${paints[0].line}  color: ${paints[0].value} in a block that also sets`
                + ` \`${marker.prop}: ${marker.value}\` — that is running prose.`,
            );
            continue;
        }

        // Arm B — bare prose element leaf, with nothing interactive in scope.
        const throughMixin = chain.some((s) => s.startsWith('@mixin'));
        if (throughMixin) continue;
        const leafSelectors = leaf.split(',').map((s) => s.trim()).filter(Boolean);
        const proseLeaf = leafSelectors.some((s) => PROSE_LEAF_RE.test(s));
        if (proseLeaf
            && !STATE_RE.test(chainText)
            && !PSEUDO_ELEMENT_RE.test(chainText)
            && !INTERACTIVE_RE.test(chainText)) {
            primaryText.push(
                `${rel}:${paints[0].line}  color: ${paints[0].value} on \`${leaf}\``
                + ' — a bare prose element with no link, control or state in the selector.',
            );
        }
    }
}

/* ------------------------------------------------------------------ */
/*  Rule 5: substitution scope — dark must redeclare what it re-bases  */
/* ------------------------------------------------------------------ */

{
    const readVars = (f) => fs.readFileSync(path.join(VARS_DIR, f), 'utf8');
    const colorsScss = readVars('_colors.scss');
    const tokensScss = readVars('_tokens.scss');

    // The blocks that constitute each theme, named as they appear in source so
    // a failure points at a place a human can open.
    const lightScopes = [
        ['_colors.scss @mixin iwac-light-theme', extractMixinBody(colorsScss, 'iwac-light-theme')],
        ['_tokens.scss @mixin iwac-light-tokens', extractMixinBody(tokensScss, 'iwac-light-tokens')],
        ['_tokens.scss :root', extractRootBody(tokensScss)],
        ['_typography.scss :root', extractRootBody(readVars('_typography.scss'))],
        ['_layout.scss :root', extractRootBody(readVars('_layout.scss'))],
    ];
    const darkScopes = [
        ['_colors.scss @mixin iwac-dark-theme', extractMixinBody(colorsScss, 'iwac-dark-theme')],
        ['_tokens.scss @mixin iwac-dark-tokens', extractMixinBody(tokensScss, 'iwac-dark-tokens')],
    ];

    const flips = new Set();
    for (const [, body] of darkScopes) for (const d of parseDecls(body)) flips.add(d.name);

    // 5b. SYMMETRY. The manual toggle applies the light mixins to <body> to win
    // back against a system-dark override already sitting on :root — so every
    // token the DARK mixins declare must be declared in the LIGHT mixins too,
    // or there is nothing on <body> to win it back with and a manually-lightened
    // page on a dark OS keeps the dark value.
    //
    // This is the mirror of rule 5, and it is how the 2.13 focus fix stayed half
    // done for a release: --focus-outline / --ring-focus / --ring-focus-sm were
    // added to the dark block only, which fixed light-OS-plus-manual-dark and
    // left dark-OS-plus-manual-light painting the dark focus colour on a light
    // page. Fixing one direction of a two-directional toggle looks like a fix.
    //
    // The converse is NOT asserted: a token in the light mixins only (--white,
    // --black) is a theme-independent constant that dark never contests, so
    // there is nothing to win back.
    const lightMixinNames = new Set();
    for (const [where, body] of lightScopes) {
        if (!where.includes('@mixin')) continue;
        for (const d of parseDecls(body)) lightMixinNames.add(d.name);
    }
    for (const [where, body] of darkScopes) {
        for (const { name } of parseDecls(body)) {
            if (lightMixinNames.has(name)) continue;
            scopeFailures.push(
                `${where}  ${name} is declared in the dark mixins but NOT in the light ones —\n`
                + '      so body[data-theme="light"] on a dark-preference OS has nothing to win\n'
                + `      back with and keeps the DARK ${name}. Declare it in the light mixin too.`,
            );
        }
    }

    for (const [where, body] of lightScopes) {
        for (const { name, value } of parseDecls(body)) {
            if (flips.has(name)) continue; // redeclared in dark — correct
            const refs = [...new Set(
                [...value.matchAll(/var\(\s*(--[\w-]+)/g)].map((m) => m[1]),
            )].filter((r) => flips.has(r));
            if (!refs.length) continue;
            scopeFailures.push(
                `${where}  ${name}: ${value.replace(/\s+/g, ' ')}\n`
                + `      references ${refs.join(', ')}, which the dark block redeclares — so ${name}\n`
                + '      freezes at the LIGHT composition on any element the dark block does not\n'
                + `      also touch. Redeclare ${name} in the dark block (move it into the theme\n`
                + '      mixin pair), or compose it from something theme-independent.',
            );
        }
    }
}

/* ------------------------------------------------------------------ */
/*  Rules 6-7: artifacts that restate tokens.json                      */
/*                                                                    */
/*  NOTE the ordering inside `npm run build`: check:tokens runs BEFORE */
/*  build:tokens, so on the very build that changes a token this reads */
/*  the PREVIOUS tokens.json. That is why each failure message names   */
/*  both sides and says which command refreshes the artifact — the     */
/*  guards are exact in steady state, and drift can survive at most    */
/*  one build.                                                        */
/* ------------------------------------------------------------------ */

const artifactFailures = [];
let tokens = null;
try {
    tokens = JSON.parse(fs.readFileSync(TOKENS_JSON, 'utf8'));
} catch (e) {
    artifactFailures.push(`tokens.json is unreadable (${e.message}) — run \`npm run build:tokens\``);
}

// tokens.json publishes 6-digit lowercase; accept shorthand in the artifacts.
function normalizeHex(hex) {
    const h = hex.trim().toLowerCase();
    return h.length === 4
        ? '#' + h[1] + h[1] + h[2] + h[2] + h[3] + h[3]
        : h;
}

// ---- 6. PWA theme-color metas must equal --surface for their scheme. -------
// Attribute order is fixed by the template, but don't depend on it: find any
// theme-color meta, read the scheme out of its media query and the value out of
// its content attribute.
const THEME_COLOR_RE = /<meta\s+[^>]*name="theme-color"[^>]*>/gi;
const SCHEME_RE = /prefers-color-scheme:\s*(light|dark)\s*\)/i;
const CONTENT_RE = /content="\s*(#[0-9a-f]{3,8})\s*"/i;

if (tokens) {
    const layoutSrc = fs.readFileSync(path.join(ROOT, LAYOUT_PHTML), 'utf8');
    const found = new Map();
    for (const match of layoutSrc.matchAll(THEME_COLOR_RE)) {
        const tag = match[0];
        const scheme = SCHEME_RE.exec(tag);
        const content = CONTENT_RE.exec(tag);
        if (!scheme || !content) {
            artifactFailures.push(
                `${LAYOUT_PHTML}  theme-color meta with no readable colour scheme or content: ${tag.trim()}`,
            );
            continue;
        }
        found.set(scheme[1].toLowerCase(), normalizeHex(content[1]));
    }

    for (const scheme of ['light', 'dark']) {
        const expected = tokens[scheme] && tokens[scheme]['--surface'];
        const actual = found.get(scheme);
        if (!expected) {
            artifactFailures.push(`tokens.json has no ${scheme}['--surface'] — run \`npm run build:tokens\``);
        } else if (!actual) {
            artifactFailures.push(
                `${LAYOUT_PHTML}  missing <meta name="theme-color" media="(prefers-color-scheme: ${scheme})"> — the PWA status bar must state --surface (${expected})`,
            );
        } else if (actual !== normalizeHex(expected)) {
            artifactFailures.push(
                `${LAYOUT_PHTML}  theme-color (${scheme}) is ${actual} but tokens.json ${scheme}['--surface'] is ${normalizeHex(expected)} — update the meta, or run \`npm run build:tokens\` first if you just changed --surface`,
            );
        }
    }
}

// ---- 6b. The generated SVG favicon must paint the light --surface. --------
const FAVICON_SVG = path.join('asset', 'img', 'pwa', 'favicon.svg');
const FAVICON_TILE_RE = /<rect\s+[^>]*class="tile"[^>]*fill="\s*(#[0-9a-f]{3,8})\s*"/i;
// The icon set is light in both schemes; a dark rule creeping back in is a
// regression, not an upgrade — 2.17.0 shipped one and it read badly at 32px.
const FAVICON_SCHEME_RE = /prefers-color-scheme/i;

if (tokens) {
    const faviconPath = path.join(ROOT, FAVICON_SVG);
    const expected = tokens.light && tokens.light['--surface'];
    if (!fs.existsSync(faviconPath)) {
        artifactFailures.push(`${FAVICON_SVG} is missing — run \`npm run build:icons\``);
    } else if (!expected) {
        artifactFailures.push("tokens.json has no light['--surface'] — run `npm run build:tokens`");
    } else {
        const svg = fs.readFileSync(faviconPath, 'utf8');
        const found = FAVICON_TILE_RE.exec(svg);
        if (!found) {
            artifactFailures.push(
                `${FAVICON_SVG}  no tile colour on the class="tile" rect — regenerate with \`npm run build:icons\``,
            );
        } else if (normalizeHex(found[1]) !== normalizeHex(expected)) {
            artifactFailures.push(
                `${FAVICON_SVG}  tile is ${normalizeHex(found[1])} but tokens.json light['--surface'] is ${normalizeHex(expected)} — run \`npm run build:icons\` (the PNGs beside it are stale too)`,
            );
        }
        if (FAVICON_SCHEME_RE.test(svg)) {
            artifactFailures.push(
                `${FAVICON_SVG}  carries a prefers-color-scheme rule — the icon set is deliberately light in both schemes (see faviconSvg() in scripts/gen-pwa-icons.js)`,
            );
        }
    }
}

// ---- 6c. The hero duotone recipe the screenshot generator replays. --------
//
// The manifest's install-dialog screenshots are the homepage hero, composited
// offline by scripts/gen-pwa-icons.js from the numbers in lib/hero-duotone.js.
// That makes them a copy of _banner.scss that no build step can notice going
// stale — the PNG/WebP holds the result in pixels. So assert the stylesheet
// still spells the recipe, with whitespace collapsed so reformatting is free.
const DUOTONE = require('./lib/hero-duotone');
const collapse = (s) => s.replace(/\s+/g, ' ');

{
    const scssPath = path.join(ROOT, DUOTONE.SCSS_FILE);
    if (!fs.existsSync(scssPath)) {
        artifactFailures.push(`${DUOTONE.SCSS_FILE} is missing — scripts/lib/hero-duotone.js points at it`);
    } else {
        const scss = collapse(fs.readFileSync(scssPath, 'utf8'));
        for (const key of ['SCSS_GROUND', 'SCSS_FILTER', 'SCSS_OPACITY']) {
            if (!scss.includes(collapse(DUOTONE[key]))) {
                artifactFailures.push(
                    `${DUOTONE.SCSS_FILE} no longer declares \`${DUOTONE[key]}\` — the hero duotone changed, so the`
                    + ' PWA screenshots are stale: update scripts/lib/hero-duotone.js and run `npm run build:icons`',
                );
            }
        }
    }
}

// ---- 7. DESIGN.md frontmatter must equal tokens.json LIGHT. ---------------
//
// DESIGN.md is the Impeccable skill's machine-readable artifact and is
// GENERATED — by `/impeccable document`, from the shipped tree. Its YAML
// frontmatter restates the light palette and two literal scales, which makes
// it one more unasserted copy of tokens.json (roadmap Phase 4, item 1).
//
// Scope, deliberately: the three sections whose keys map 1:1 onto token names
// — `colors:` → light[--<key>], `rounded:` → --radius-*, `spacing:` →
// --space-*. The `typography:` and `components:` sections are editorial
// groupings (a shortened font stack, a role name like "headline" chosen for
// the tooling rather than a token), so there is no name to compare them by;
// they are the documenter's to own. Nor is the reverse asserted — the
// frontmatter lists a curated subset, and it is not a bug for it to omit
// --black or the --footer-* family.
const DESIGN_MD_SECTIONS = [
    ['colors', (k) => `--${k}`, (t, name) => t.light[name]],
    ['rounded', (k) => `--radius-${k}`, (t, name) => t.values.light[name]],
    ['spacing', (k) => `--space-${k}`, (t, name) => t.values.light[name]],
];

function readFrontmatterSections(md) {
    const m = /^---\r?\n([\s\S]*?)\r?\n---\r?\n/.exec(md);
    if (!m) return null;
    const sections = {};
    let current = null;
    for (const raw of m[1].split(/\r?\n/)) {
        const top = /^([a-z][\w-]*):\s*$/i.exec(raw);
        if (top) { current = top[1]; sections[current] = {}; continue; }
        if (/^\S/.test(raw)) { current = null; continue; }
        const entry = /^ {2}([\w-]+):\s*"?([^"\n]*?)"?\s*$/.exec(raw);
        if (current && entry && entry[2] !== '') sections[current][entry[1]] = entry[2];
    }
    return sections;
}

const designMdFailures = [];
if (tokens && fs.existsSync(DESIGN_MD)) {
    const sections = readFrontmatterSections(fs.readFileSync(DESIGN_MD, 'utf8'));
    if (!sections) {
        designMdFailures.push('DESIGN.md has no YAML frontmatter to compare');
    } else {
        for (const [section, toName, lookup] of DESIGN_MD_SECTIONS) {
            const entries = sections[section];
            if (!entries) {
                designMdFailures.push(`DESIGN.md frontmatter has no \`${section}:\` section`);
                continue;
            }
            for (const [key, stated] of Object.entries(entries)) {
                const name = toName(key);
                const canonical = lookup(tokens, name);
                if (canonical === undefined) {
                    designMdFailures.push(
                        `DESIGN.md ${section}.${key} names ${name}, which tokens.json does not publish`,
                    );
                } else if (normalizeHex(stated) !== normalizeHex(String(canonical))) {
                    designMdFailures.push(
                        `DESIGN.md ${section}.${key} is "${stated}" but tokens.json light ${name} is "${canonical}"`,
                    );
                }
            }
        }
    }
}

